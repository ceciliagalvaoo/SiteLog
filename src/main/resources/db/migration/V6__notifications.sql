-- V6: in-app notifications (no e-mail).
--
-- A notification is addressed to one user and shown under the bell icon in the top bar until
-- it is marked as read. They are produced by the scheduled jobs (overdue corrective actions,
-- unsigned daily logs) and by domain events (reopen requested, HIGH/CRITICAL incident).
--
-- Same conventions as V2/V3: singular snake_case names, bigint identity key, enumeration as
-- varchar + CHECK matching the Java enum NotificationType, no ON DELETE CASCADE.

CREATE TABLE notification (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id bigint       NOT NULL,
    type         varchar(40)  NOT NULL,
    title        varchar(200) NOT NULL,
    body         varchar(1000),
    -- Relative application path the notification opens (e.g. /daily-logs/42), never an external URL.
    link         varchar(500),
    created_at   timestamptz  NOT NULL DEFAULT now(),
    -- NULL while unread; set once when the recipient marks it as read.
    read_at      timestamptz,
    CONSTRAINT ck_notification_type CHECK (type IN (
        'CORRECTIVE_ACTION_OVERDUE', 'DAILY_LOG_UNSIGNED', 'REOPEN_REQUESTED', 'HIGH_SEVERITY_INCIDENT')),
    CONSTRAINT ck_notification_title CHECK (btrim(title) <> ''),
    CONSTRAINT ck_notification_link_relative CHECK (link IS NULL OR (link LIKE '/%' AND link NOT LIKE '//%')),
    CONSTRAINT fk_notification_recipient FOREIGN KEY (recipient_id) REFERENCES app_user (id)
);

-- Serves the two queries behind the bell on every page: "unread notifications of user X"
-- (recipient_id = ? AND read_at IS NULL) and the unread counter. The leading recipient_id
-- column also covers the foreign key.
CREATE INDEX ix_notification_recipient_read ON notification (recipient_id, read_at);
