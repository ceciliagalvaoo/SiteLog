-- V3: incidents, corrective actions, reopen requests, AI incident drafts,
-- the database lock for signed-off daily logs, and the Hibernate Envers audit tables.

-- ===========================================================================
-- 1. Incident aggregate
-- ===========================================================================
CREATE TABLE incident (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id            bigint       NOT NULL,
    -- optional relation: an incident may be linked to the daily log of that day
    daily_log_id       bigint,
    occurred_at        timestamptz  NOT NULL,
    title              varchar(200) NOT NULL,
    description        text         NOT NULL,
    severity           varchar(10)  NOT NULL,
    category           varchar(30)  NOT NULL,
    status             varchar(20)  NOT NULL DEFAULT 'REPORTED',
    -- required for HIGH and CRITICAL before sign-off (see ck_incident_severity_fields)
    root_cause         text,
    witnesses          text,
    medical_treatment  text,
    authority_notified boolean,
    reported_by        bigint       NOT NULL,
    signed_off_by      bigint,
    signed_off_at      timestamptz,
    version            bigint       NOT NULL DEFAULT 0,
    CONSTRAINT ck_incident_severity CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT ck_incident_category CHECK (category IN (
        'FALL_FROM_HEIGHT', 'STRUCK_BY_OBJECT', 'MACHINERY', 'ELECTRICAL', 'MANUAL_HANDLING',
        'SLIP_TRIP', 'FIRE_EXPLOSION', 'ENVIRONMENTAL', 'NEAR_MISS', 'OTHER')),
    CONSTRAINT ck_incident_status CHECK (status IN ('REPORTED', 'UNDER_REVIEW', 'SIGNED_OFF', 'CLOSED')),
    -- AR2 safety net: a HIGH/CRITICAL incident cannot reach SIGNED_OFF or CLOSED without the
    -- four extra fields. The service validates first and returns a field-level message (422);
    -- this constraint only guarantees that no code path can skip that validation.
    CONSTRAINT ck_incident_severity_fields CHECK (
        severity IN ('LOW', 'MEDIUM')
        OR status IN ('REPORTED', 'UNDER_REVIEW')
        OR (nullif(btrim(root_cause), '') IS NOT NULL
            AND nullif(btrim(witnesses), '') IS NOT NULL
            AND nullif(btrim(medical_treatment), '') IS NOT NULL
            AND authority_notified IS NOT NULL)),
    -- a signed-off (or closed) incident always records who signed it and when
    CONSTRAINT ck_incident_signed_off CHECK (
        status IN ('REPORTED', 'UNDER_REVIEW') OR (signed_off_by IS NOT NULL AND signed_off_at IS NOT NULL)),
    CONSTRAINT fk_incident_site FOREIGN KEY (site_id) REFERENCES site (id),
    CONSTRAINT fk_incident_daily_log FOREIGN KEY (daily_log_id) REFERENCES daily_log (id),
    CONSTRAINT fk_incident_reported_by FOREIGN KEY (reported_by) REFERENCES app_user (id),
    CONSTRAINT fk_incident_signed_off_by FOREIGN KEY (signed_off_by) REFERENCES app_user (id)
);

CREATE INDEX ix_incident_site ON incident (site_id);
CREATE INDEX ix_incident_daily_log ON incident (daily_log_id);
CREATE INDEX ix_incident_reported_by ON incident (reported_by);
CREATE INDEX ix_incident_signed_off_by ON incident (signed_off_by);

-- Many-to-many without attributes: Incident <-> Crew (affected crews)
CREATE TABLE incident_affected_crew (
    incident_id bigint NOT NULL,
    crew_id     bigint NOT NULL,
    CONSTRAINT pk_incident_affected_crew PRIMARY KEY (incident_id, crew_id),
    CONSTRAINT fk_incident_affected_crew_incident FOREIGN KEY (incident_id) REFERENCES incident (id),
    CONSTRAINT fk_incident_affected_crew_crew FOREIGN KEY (crew_id) REFERENCES crew (id)
);

CREATE INDEX ix_incident_affected_crew_crew ON incident_affected_crew (crew_id);

CREATE TABLE corrective_action (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id  bigint       NOT NULL,
    description  varchar(500) NOT NULL,
    -- optional relation: an action may not have an assignee yet
    assignee_id  bigint,
    due_date     date         NOT NULL,
    status       varchar(10)  NOT NULL DEFAULT 'OPEN',
    completed_at timestamptz,
    CONSTRAINT ck_corrective_action_status CHECK (status IN ('OPEN', 'DONE', 'OVERDUE')),
    -- completed_at is set exactly when the action is DONE
    CONSTRAINT ck_corrective_action_completed CHECK ((status = 'DONE') = (completed_at IS NOT NULL)),
    CONSTRAINT fk_corrective_action_incident FOREIGN KEY (incident_id) REFERENCES incident (id),
    CONSTRAINT fk_corrective_action_assignee FOREIGN KEY (assignee_id) REFERENCES app_user (id)
);

CREATE INDEX ix_corrective_action_incident ON corrective_action (incident_id);
CREATE INDEX ix_corrective_action_assignee ON corrective_action (assignee_id);

-- ===========================================================================
-- 2. Reopen requests (AR1: why a signed-off log was reopened and who approved it)
-- ===========================================================================
CREATE TABLE log_reopen_request (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    daily_log_id bigint      NOT NULL,
    reason       text        NOT NULL,
    requested_by bigint      NOT NULL,
    -- the supervisor who decided (approved or rejected); null while PENDING
    approved_by  bigint,
    requested_at timestamptz NOT NULL DEFAULT now(),
    decided_at   timestamptz,
    status       varchar(10) NOT NULL DEFAULT 'PENDING',
    CONSTRAINT ck_log_reopen_request_reason CHECK (btrim(reason) <> ''),
    CONSTRAINT ck_log_reopen_request_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    -- PENDING has no decision yet; APPROVED/REJECTED always record who decided and when
    CONSTRAINT ck_log_reopen_request_decision CHECK (
        (status = 'PENDING' AND approved_by IS NULL AND decided_at IS NULL)
        OR (status <> 'PENDING' AND approved_by IS NOT NULL AND decided_at IS NOT NULL)),
    CONSTRAINT ck_log_reopen_request_dates CHECK (decided_at IS NULL OR decided_at >= requested_at),
    CONSTRAINT fk_log_reopen_request_daily_log FOREIGN KEY (daily_log_id) REFERENCES daily_log (id),
    CONSTRAINT fk_log_reopen_request_requested_by FOREIGN KEY (requested_by) REFERENCES app_user (id),
    CONSTRAINT fk_log_reopen_request_approved_by FOREIGN KEY (approved_by) REFERENCES app_user (id)
);

CREATE INDEX ix_log_reopen_request_daily_log ON log_reopen_request (daily_log_id);
CREATE INDEX ix_log_reopen_request_requested_by ON log_reopen_request (requested_by);
CREATE INDEX ix_log_reopen_request_approved_by ON log_reopen_request (approved_by);
-- at most one open (PENDING) request per daily log
CREATE UNIQUE INDEX uk_log_reopen_request_pending
    ON log_reopen_request (daily_log_id) WHERE status = 'PENDING';

-- ===========================================================================
-- 3. Incident drafts (AI output; becomes an Incident only after a supervisor accepts it)
-- ===========================================================================
CREATE TABLE incident_draft (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id          bigint      NOT NULL,
    shift_note       text        NOT NULL,
    -- suggested by the AI; null when the output was invalid or incomplete
    severity         varchar(10),
    category         varchar(30),
    affected_crews   text,
    immediate_action text,
    status           varchar(20) NOT NULL,
    created_by       bigint      NOT NULL,
    reviewed_by      bigint,
    incident_id      bigint,
    created_at       timestamptz NOT NULL DEFAULT now(),
    reviewed_at      timestamptz,
    CONSTRAINT uk_incident_draft_incident UNIQUE (incident_id),
    CONSTRAINT ck_incident_draft_shift_note CHECK (btrim(shift_note) <> ''),
    CONSTRAINT ck_incident_draft_severity CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT ck_incident_draft_category CHECK (category IN (
        'FALL_FROM_HEIGHT', 'STRUCK_BY_OBJECT', 'MACHINERY', 'ELECTRICAL', 'MANUAL_HANDLING',
        'SLIP_TRIP', 'FIRE_EXPLOSION', 'ENVIRONMENTAL', 'NEAR_MISS', 'OTHER')),
    CONSTRAINT ck_incident_draft_status CHECK (
        status IN ('PENDING_REVIEW', 'NEEDS_MANUAL_INPUT', 'ACCEPTED', 'REJECTED')),
    -- a decided draft records the reviewer; only an ACCEPTED draft points to an incident
    CONSTRAINT ck_incident_draft_review CHECK (
        status IN ('PENDING_REVIEW', 'NEEDS_MANUAL_INPUT')
        OR (reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL)),
    CONSTRAINT ck_incident_draft_incident CHECK ((status = 'ACCEPTED') = (incident_id IS NOT NULL)),
    CONSTRAINT fk_incident_draft_site FOREIGN KEY (site_id) REFERENCES site (id),
    CONSTRAINT fk_incident_draft_created_by FOREIGN KEY (created_by) REFERENCES app_user (id),
    CONSTRAINT fk_incident_draft_reviewed_by FOREIGN KEY (reviewed_by) REFERENCES app_user (id),
    CONSTRAINT fk_incident_draft_incident FOREIGN KEY (incident_id) REFERENCES incident (id)
);

CREATE INDEX ix_incident_draft_site ON incident_draft (site_id);
CREATE INDEX ix_incident_draft_created_by ON incident_draft (created_by);
CREATE INDEX ix_incident_draft_reviewed_by ON incident_draft (reviewed_by);

-- ===========================================================================
-- 4. Lock for signed-off daily logs (AR1, second layer after the service check)
--
-- Every violation raises SQLSTATE P0001 (raise_exception) with MESSAGE 'daily_log_locked';
-- the application maps that message to its domain exception (HTTP 409).
-- ===========================================================================

-- Raises daily_log_locked when the given log is SIGNED_OFF.
CREATE FUNCTION assert_daily_log_editable(p_daily_log_id bigint) RETURNS void
LANGUAGE plpgsql AS $$
DECLARE
    v_status varchar(20);
BEGIN
    SELECT status INTO v_status FROM daily_log WHERE id = p_daily_log_id;
    -- a missing parent (v_status IS NULL) is left to the foreign key to report
    IF v_status = 'SIGNED_OFF' THEN
        RAISE EXCEPTION USING
            ERRCODE = 'P0001',
            MESSAGE = 'daily_log_locked',
            DETAIL  = format('daily_log %s is SIGNED_OFF', p_daily_log_id),
            HINT    = 'Request a reopen of the daily log first.';
    END IF;
END;
$$;

-- daily_log: while a row is SIGNED_OFF the only change accepted is the reopen, i.e.
--   status SIGNED_OFF -> REOPENED, revision + 1, content (site, date, weather, notes) unchanged;
--   version and the sign-off columns may change in that same statement.
-- Everything else on a SIGNED_OFF row fails, including a version-only update
-- (OPTIMISTIC_FORCE_INCREMENT is only issued when a child changes, and children are locked).
-- Rows in DRAFT or REOPENED are not restricted, so the sign-off itself
-- (DRAFT/REOPENED -> SIGNED_OFF) passes. DELETE of a SIGNED_OFF log fails.
CREATE FUNCTION daily_log_lock_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.status <> 'SIGNED_OFF' THEN
        IF TG_OP = 'DELETE' THEN
            RETURN OLD;
        END IF;
        RETURN NEW;
    END IF;

    IF TG_OP = 'UPDATE'
       AND NEW.status = 'REOPENED'
       AND NEW.revision = OLD.revision + 1
       AND NEW.site_id = OLD.site_id
       AND NEW.log_date = OLD.log_date
       AND NEW.weather IS NOT DISTINCT FROM OLD.weather
       AND NEW.notes IS NOT DISTINCT FROM OLD.notes THEN
        RETURN NEW;
    END IF;

    RAISE EXCEPTION USING
        ERRCODE = 'P0001',
        MESSAGE = 'daily_log_locked',
        DETAIL  = format('daily_log %s is SIGNED_OFF (%s rejected)', OLD.id, TG_OP),
        HINT    = 'Request a reopen of the daily log first.';
END;
$$;

CREATE TRIGGER trg_daily_log_lock
    BEFORE UPDATE OR DELETE ON daily_log
    FOR EACH ROW EXECUTE FUNCTION daily_log_lock_guard();

-- work_entry: INSERT/UPDATE/DELETE fail when the parent log is SIGNED_OFF.
-- On UPDATE both the old and the new parent are checked (moving an entry between logs).
CREATE FUNCTION work_entry_lock_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP IN ('UPDATE', 'DELETE') THEN
        PERFORM assert_daily_log_editable(OLD.daily_log_id);
    END IF;
    IF TG_OP IN ('INSERT', 'UPDATE') THEN
        PERFORM assert_daily_log_editable(NEW.daily_log_id);
        RETURN NEW;
    END IF;
    RETURN OLD;
END;
$$;

CREATE TRIGGER trg_work_entry_lock
    BEFORE INSERT OR UPDATE OR DELETE ON work_entry
    FOR EACH ROW EXECUTE FUNCTION work_entry_lock_guard();

-- crew_assignment: same rule, the parent log is found through work_entry.
CREATE FUNCTION crew_assignment_lock_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP IN ('UPDATE', 'DELETE') THEN
        PERFORM assert_daily_log_editable(
            (SELECT daily_log_id FROM work_entry WHERE id = OLD.work_entry_id));
    END IF;
    IF TG_OP IN ('INSERT', 'UPDATE') THEN
        PERFORM assert_daily_log_editable(
            (SELECT daily_log_id FROM work_entry WHERE id = NEW.work_entry_id));
        RETURN NEW;
    END IF;
    RETURN OLD;
END;
$$;

CREATE TRIGGER trg_crew_assignment_lock
    BEFORE INSERT OR UPDATE OR DELETE ON crew_assignment
    FOR EACH ROW EXECUTE FUNCTION crew_assignment_lock_guard();

-- ===========================================================================
-- 5. Hibernate Envers audit tables (AR1: what changed, by whom, when)
--
-- Envers defaults (Hibernate 7): audit table = entity table + suffix "_AUD", revision column
-- "REV", revision type column "REVTYPE" (TINYINT -> smallint on PostgreSQL; 0 = ADD, 1 = MOD,
-- 2 = DEL); the physical naming strategy lower-cases the names. The @Version column is not
-- audited (do_not_audit_optimistic_locking_field = true). Audited columns are nullable because
-- Envers writes a DEL row with only id/rev/revtype. Audit rows have no foreign keys to the
-- domain tables, so history survives when the audited row or its references are deleted.
-- ===========================================================================

-- Custom revision entity: one row per transaction that changed audited data.
CREATE TABLE revinfo (
    rev      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- epoch milliseconds (@RevisionTimestamp long)
    revtstmp bigint NOT NULL,
    -- email of the authenticated user, filled by the RevisionListener
    username varchar(255)
);

CREATE TABLE daily_log_aud (
    id            bigint   NOT NULL,
    rev           bigint   NOT NULL,
    revtype       smallint,
    site_id       bigint,
    log_date      date,
    status        varchar(20),
    revision      integer,
    weather       varchar(20),
    notes         text,
    signed_off_by bigint,
    signed_off_at timestamptz,
    CONSTRAINT pk_daily_log_aud PRIMARY KEY (id, rev),
    CONSTRAINT fk_daily_log_aud_rev FOREIGN KEY (rev) REFERENCES revinfo (rev)
);

CREATE TABLE work_entry_aud (
    id           bigint   NOT NULL,
    rev          bigint   NOT NULL,
    revtype      smallint,
    daily_log_id bigint,
    description  varchar(500),
    location     varchar(150),
    start_time   time,
    end_time     time,
    CONSTRAINT pk_work_entry_aud PRIMARY KEY (id, rev),
    CONSTRAINT fk_work_entry_aud_rev FOREIGN KEY (rev) REFERENCES revinfo (rev)
);

CREATE TABLE crew_assignment_aud (
    id            bigint   NOT NULL,
    rev           bigint   NOT NULL,
    revtype       smallint,
    work_entry_id bigint,
    crew_id       bigint,
    hours_worked  numeric(4,2),
    worker_count  integer,
    task          varchar(255),
    CONSTRAINT pk_crew_assignment_aud PRIMARY KEY (id, rev),
    CONSTRAINT fk_crew_assignment_aud_rev FOREIGN KEY (rev) REFERENCES revinfo (rev)
);

-- "history of one log" and "changes in one revision" lookups
CREATE INDEX ix_daily_log_aud_rev ON daily_log_aud (rev);
CREATE INDEX ix_work_entry_aud_rev ON work_entry_aud (rev);
CREATE INDEX ix_work_entry_aud_daily_log ON work_entry_aud (daily_log_id);
CREATE INDEX ix_crew_assignment_aud_rev ON crew_assignment_aud (rev);
CREATE INDEX ix_crew_assignment_aud_work_entry ON crew_assignment_aud (work_entry_id);
