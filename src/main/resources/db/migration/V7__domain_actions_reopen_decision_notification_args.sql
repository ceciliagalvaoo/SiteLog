-- V7: what the M3 workflows need on top of V3/V5/V6.
--
--   1. domain_action      - one row per intercepted domain action (the @AuditedAction aspect):
--                           who did what, to which record, when, and how it ended. Append-only,
--                           like the Envers tables (V5).
--   2. log_reopen_request - decision_note: the supervisor's reason, mandatory when a reopen
--                           request is REJECTED (AR1: "a defensible process" both ways).
--   3. notification       - body_key + body_args: the body is stored as a message key with
--                           arguments and rendered in the reader's language (decision 08/11).
--
-- Same conventions as V2-V6: singular snake_case, bigint identity key, enumerations as
-- varchar + CHECK matching the Java enum, no ON DELETE CASCADE.

-- ===========================================================================
-- 1. Domain action log (third layer of the reopen audit trail, ADR-0003 decision 6)
--
-- Envers answers "what changed in the data", log_reopen_request "why and who approved";
-- this table answers "which action happened, by whom, when, with which outcome" for sign-off,
-- reopen request / approval / rejection, incident transitions and corrective actions.
-- entity_id has no foreign key on purpose: the target table depends on entity_type, and the
-- record of an action must survive the deletion of its target (e.g. a deleted incident).
-- ===========================================================================
CREATE TABLE domain_action (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action      varchar(40)  NOT NULL,
    entity_type varchar(30)  NOT NULL,
    entity_id   bigint,
    -- null for a call without a signed-in user (scheduled job); the e-mail is kept as text too,
    -- so the row stays readable even if the user is renamed
    actor_id    bigint,
    actor_email varchar(255),
    occurred_at timestamptz  NOT NULL DEFAULT now(),
    outcome     varchar(10)  NOT NULL,
    duration_ms integer      NOT NULL DEFAULT 0,
    -- exception class or message key for a refused / failed call; null on success
    detail      varchar(500),
    CONSTRAINT ck_domain_action_action CHECK (action IN (
        'LOG_SIGNED_OFF', 'LOG_REOPEN_REQUESTED', 'LOG_REOPEN_APPROVED', 'LOG_REOPEN_REJECTED',
        'INCIDENT_REPORTED', 'INCIDENT_UPDATED', 'INCIDENT_REVIEW_STARTED', 'INCIDENT_SIGNED_OFF',
        'INCIDENT_CLOSED', 'INCIDENT_DELETED',
        'CORRECTIVE_ACTION_ADDED', 'CORRECTIVE_ACTION_UPDATED', 'CORRECTIVE_ACTION_DONE',
        'CORRECTIVE_ACTION_DELETED')),
    CONSTRAINT ck_domain_action_entity_type CHECK (entity_type IN ('DAILY_LOG', 'INCIDENT')),
    CONSTRAINT ck_domain_action_outcome CHECK (outcome IN ('SUCCESS', 'REJECTED', 'DENIED', 'FAILED')),
    CONSTRAINT ck_domain_action_duration CHECK (duration_ms >= 0),
    CONSTRAINT fk_domain_action_actor FOREIGN KEY (actor_id) REFERENCES app_user (id)
);

-- "timeline of one record" (incident detail, daily log history), oldest first
CREATE INDEX ix_domain_action_entity ON domain_action (entity_type, entity_id, occurred_at);
CREATE INDEX ix_domain_action_actor ON domain_action (actor_id);

-- Append-only, same guard function and message as the Envers tables (V5).
CREATE TRIGGER trg_domain_action_append_only
    BEFORE UPDATE OR DELETE ON domain_action
    FOR EACH ROW EXECUTE FUNCTION audit_append_only_guard();

CREATE TRIGGER trg_domain_action_no_truncate
    BEFORE TRUNCATE ON domain_action
    FOR EACH STATEMENT EXECUTE FUNCTION audit_append_only_guard();

-- ===========================================================================
-- 2. Reason of the supervisor's decision on a reopen request
-- ===========================================================================
ALTER TABLE log_reopen_request ADD COLUMN decision_note text;

-- The V4 demo data has one REJECTED request recorded before this column existed; give it a
-- note so the new rule holds for every row.
UPDATE log_reopen_request
SET decision_note = 'Not a correction of recorded work: add the crane stop to the next daily log.'
WHERE status = 'REJECTED' AND decision_note IS NULL;

-- A rejection always says why; an approval may add a note; a PENDING request has none yet.
ALTER TABLE log_reopen_request ADD CONSTRAINT ck_log_reopen_request_decision_note CHECK (
    (status = 'PENDING' AND decision_note IS NULL)
    OR status = 'APPROVED'
    OR (status = 'REJECTED' AND nullif(btrim(decision_note), '') IS NOT NULL));

-- ===========================================================================
-- 3. Translatable notification body
--
-- body_key:  message key, e.g. notification.body.REOPEN_REQUESTED
-- body_args: its arguments, separated by the ASCII unit separator (U+001F), which never occurs
--            in the values (the application removes it); null when there are none.
-- The old free-text body column stays for rows created before V7.
-- ===========================================================================
ALTER TABLE notification ADD COLUMN body_key varchar(100);
ALTER TABLE notification ADD COLUMN body_args varchar(1000);

ALTER TABLE notification ADD CONSTRAINT ck_notification_body_args CHECK (body_args IS NULL OR body_key IS NOT NULL);
