-- V2: core schema — roles, users, sites, crews and the DailyLog aggregate
-- (daily_log -> work_entry -> crew_assignment).
--
-- Conventions used in every migration:
--   * table and column names are singular snake_case (Hibernate's default physical naming);
--   * surrogate keys are bigint identity columns;
--   * fixed enumerations are varchar + CHECK, matching @Enumerated(EnumType.STRING);
--   * foreign keys have no ON DELETE CASCADE: deletes are decided by the service layer,
--     so a delete that would orphan rows fails instead of silently removing data;
--   * every foreign key column that is not already the leading column of a unique
--     constraint gets an index (PostgreSQL does not create them automatically).

-- ---------------------------------------------------------------------------
-- Roles (reference data, needed in every environment)
-- ---------------------------------------------------------------------------
CREATE TABLE role (
    id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(30) NOT NULL,
    CONSTRAINT uk_role_name UNIQUE (name),
    CONSTRAINT ck_role_name CHECK (name IN ('ADMIN', 'SITE_MANAGER', 'SAFETY_SUPERVISOR', 'INSPECTOR'))
);

INSERT INTO role (name) VALUES ('ADMIN'), ('SITE_MANAGER'), ('SAFETY_SUPERVISOR'), ('INSPECTOR');

-- ---------------------------------------------------------------------------
-- Users
-- ---------------------------------------------------------------------------
CREATE TABLE app_user (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email              varchar(255) NOT NULL,
    password_hash      varchar(100) NOT NULL,
    full_name          varchar(150) NOT NULL,
    preferred_language varchar(2)   NOT NULL DEFAULT 'en',
    active             boolean      NOT NULL DEFAULT true,
    role_id            bigint       NOT NULL,
    CONSTRAINT uk_app_user_email UNIQUE (email),
    -- emails are stored lower-case so the unique constraint is case-insensitive in practice
    CONSTRAINT ck_app_user_email_lower CHECK (email = lower(email)),
    CONSTRAINT ck_app_user_language CHECK (preferred_language IN ('en', 'hr')),
    CONSTRAINT fk_app_user_role FOREIGN KEY (role_id) REFERENCES role (id)
);

CREATE INDEX ix_app_user_role ON app_user (role_id);

-- ---------------------------------------------------------------------------
-- Sites
-- ---------------------------------------------------------------------------
CREATE TABLE site (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       varchar(20)  NOT NULL,
    name       varchar(150) NOT NULL,
    address    varchar(255) NOT NULL,
    -- optional free text shown on the site detail and the site form
    description varchar(1000),
    start_date date         NOT NULL,
    end_date   date,
    -- must reference a SITE_MANAGER user; the role is checked by the service (a CHECK
    -- constraint cannot look at another table)
    manager_id bigint       NOT NULL,
    CONSTRAINT uk_site_code UNIQUE (code),
    CONSTRAINT ck_site_dates CHECK (end_date IS NULL OR end_date >= start_date),
    CONSTRAINT fk_site_manager FOREIGN KEY (manager_id) REFERENCES app_user (id)
);

CREATE INDEX ix_site_manager ON site (manager_id);

-- ---------------------------------------------------------------------------
-- Crews
-- ---------------------------------------------------------------------------
CREATE TABLE crew (
    id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    varchar(150) NOT NULL,
    company varchar(150) NOT NULL,
    trade   varchar(100) NOT NULL,
    active  boolean      NOT NULL DEFAULT true,
    CONSTRAINT uk_crew_name UNIQUE (name)
);

-- ---------------------------------------------------------------------------
-- Daily log (aggregate root, optimistic lock on "version")
-- ---------------------------------------------------------------------------
CREATE TABLE daily_log (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id       bigint      NOT NULL,
    log_date      date        NOT NULL,
    status        varchar(20) NOT NULL DEFAULT 'DRAFT',
    -- incremented by the service on each approved reopen
    revision      integer     NOT NULL DEFAULT 0,
    weather       varchar(20),
    notes         text,
    signed_off_by bigint,
    signed_off_at timestamptz,
    version       bigint      NOT NULL DEFAULT 0,
    -- one log per site and day
    CONSTRAINT uk_daily_log_site_date UNIQUE (site_id, log_date),
    CONSTRAINT ck_daily_log_status CHECK (status IN ('DRAFT', 'SIGNED_OFF', 'REOPENED')),
    CONSTRAINT ck_daily_log_weather CHECK (weather IN ('SUNNY', 'CLOUDY', 'RAIN', 'SNOW', 'WIND', 'FOG')),
    CONSTRAINT ck_daily_log_revision CHECK (revision >= 0),
    -- a signed-off log always records who signed it and when
    CONSTRAINT ck_daily_log_signed_off CHECK (
        status <> 'SIGNED_OFF' OR (signed_off_by IS NOT NULL AND signed_off_at IS NOT NULL)),
    CONSTRAINT fk_daily_log_site FOREIGN KEY (site_id) REFERENCES site (id),
    CONSTRAINT fk_daily_log_signed_off_by FOREIGN KEY (signed_off_by) REFERENCES app_user (id)
);

CREATE INDEX ix_daily_log_signed_off_by ON daily_log (signed_off_by);

-- ---------------------------------------------------------------------------
-- Work entry (child of daily_log)
-- ---------------------------------------------------------------------------
CREATE TABLE work_entry (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    daily_log_id bigint       NOT NULL,
    description  varchar(500) NOT NULL,
    location     varchar(150),
    start_time   time,
    end_time     time,
    CONSTRAINT ck_work_entry_times CHECK (start_time IS NULL OR end_time IS NULL OR end_time > start_time),
    CONSTRAINT fk_work_entry_daily_log FOREIGN KEY (daily_log_id) REFERENCES daily_log (id)
);

CREATE INDEX ix_work_entry_daily_log ON work_entry (daily_log_id);

-- ---------------------------------------------------------------------------
-- Crew assignment: association entity WorkEntry <-> Crew with attributes
-- ---------------------------------------------------------------------------
CREATE TABLE crew_assignment (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_entry_id bigint       NOT NULL,
    crew_id       bigint       NOT NULL,
    hours_worked  numeric(4,2) NOT NULL,
    worker_count  integer      NOT NULL,
    task          varchar(255),
    -- the same crew appears at most once per work entry
    CONSTRAINT uk_crew_assignment_entry_crew UNIQUE (work_entry_id, crew_id),
    CONSTRAINT ck_crew_assignment_hours CHECK (hours_worked > 0 AND hours_worked <= 24),
    CONSTRAINT ck_crew_assignment_workers CHECK (worker_count > 0),
    CONSTRAINT fk_crew_assignment_work_entry FOREIGN KEY (work_entry_id) REFERENCES work_entry (id),
    CONSTRAINT fk_crew_assignment_crew FOREIGN KEY (crew_id) REFERENCES crew (id)
);

CREATE INDEX ix_crew_assignment_crew ON crew_assignment (crew_id);
