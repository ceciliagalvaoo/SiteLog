package hr.algebra.sitelog.support;

import java.math.BigDecimal;
import java.time.Clock;
import java.time.Instant;
import java.time.LocalDate;
import java.time.ZoneId;

import org.springframework.beans.BeanUtils;
import org.springframework.test.util.ReflectionTestUtils;

import hr.algebra.sitelog.common.domain.BaseEntity;
import hr.algebra.sitelog.crew.domain.Crew;
import hr.algebra.sitelog.dailylog.domain.CrewAssignment;
import hr.algebra.sitelog.dailylog.domain.DailyLog;
import hr.algebra.sitelog.dailylog.domain.LogStatus;
import hr.algebra.sitelog.dailylog.domain.WorkEntry;
import hr.algebra.sitelog.notification.domain.Notification;
import hr.algebra.sitelog.notification.domain.NotificationType;
import hr.algebra.sitelog.site.domain.Site;
import hr.algebra.sitelog.user.domain.AppUser;
import hr.algebra.sitelog.user.domain.Role;
import hr.algebra.sitelog.user.domain.RoleName;

/**
 * In-memory entities for unit tests (no database, no Spring context). Ids and versions are
 * generated by Hibernate in production, so they are set here by reflection to mimic an entity
 * loaded from the database.
 */
public final class TestEntities {

	public static final ZoneId ZONE = ZoneId.of("Europe/Zagreb");

	/** "Now" of every unit test: 15 Nov 2026, 10:00 in Zagreb. */
	public static final Instant NOW = Instant.parse("2026-11-15T09:00:00Z");

	public static final LocalDate TODAY = LocalDate.of(2026, 11, 15);

	private TestEntities() {
	}

	public static Clock fixedClock() {
		return Clock.fixed(NOW, ZONE);
	}

	public static <T extends BaseEntity> T withId(T entity, Long id) {
		ReflectionTestUtils.setField(entity, "id", id);
		return entity;
	}

	public static Role role(RoleName name) {
		Role role = BeanUtils.instantiateClass(Role.class);
		ReflectionTestUtils.setField(role, "name", name);
		return withId(role, (long) name.ordinal() + 1);
	}

	public static AppUser user(Long id, String fullName, RoleName roleName, boolean active) {
		AppUser user = new AppUser(fullName.toLowerCase().replace(' ', '.') + "@sitelog.test", "{noop}x", fullName,
				role(roleName));
		user.setActive(active);
		return withId(user, id);
	}

	public static AppUser manager(Long id) {
		return user(id, "Marko Kovacevic", RoleName.SITE_MANAGER, true);
	}

	public static Site site(Long id, String code, AppUser manager) {
		return withId(new Site(code, "Site " + code, "Ilica 1, Zagreb", LocalDate.of(2026, 1, 1), manager), id);
	}

	public static Crew crew(Long id, String name, boolean active) {
		Crew crew = new Crew(name, "Gradnja d.o.o.", "Formwork");
		crew.setActive(active);
		return withId(crew, id);
	}

	public static DailyLog log(Long id, Site site, LocalDate date, LogStatus status, long version) {
		DailyLog log = withId(new DailyLog(site, date), id);
		log.setStatus(status);
		ReflectionTestUtils.setField(log, "version", version);
		return log;
	}

	public static WorkEntry entry(Long id, String description) {
		return withId(new WorkEntry(description), id);
	}

	public static CrewAssignment assignment(Long id, Crew crew, String hours, int workers) {
		return withId(new CrewAssignment(crew, new BigDecimal(hours), workers, "Task"), id);
	}

	public static Notification notification(Long id, AppUser recipient, String link, Instant createdAt) {
		return withId(new Notification(recipient, NotificationType.DAILY_LOG_UNSIGNED, "Unsigned log", "Body", link,
				createdAt), id);
	}

}
