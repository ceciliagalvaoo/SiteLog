// Runs in Node.js at build time. This folder (docs/) is both the Docusaurus site and its
// content, so the paths required by the assignment (docs/adr/, docs/ai-usage.md,
// docs/ai-evaluation.md, docs/design-rationale.md, ...) stay exact and every file is also
// readable directly on GitHub. Docusaurus only renders them.

// Root-level docs whose paths are fixed by the assignment, grouped into sidebar sections
// without moving the files. Key: section label; value: position and doc ids (path without .md).
const rootSections: Record<string, {position: number; docIds: string[]}> = {
  AI: {position: 5, docIds: ['ai-usage', 'ai-evaluation']},
};

const repoUrl = 'https://github.com/ceciliagalvaoo/SiteLog';

// Default autogenerated sidebar, then root-level docs listed in rootSections are wrapped in
// their own category. Everything else (folders + _category_.json) is left as generated.
const sidebarItemsGenerator: DocsPluginOptions['sidebarItemsGenerator'] = async ({
  defaultSidebarItemsGenerator,
  ...args
}) => {
  const items = await defaultSidebarItemsGenerator(args);
  if (args.item.dirName !== '.') {
    return items;
  }
  const result: typeof items = [];
  const grouped = new Map<string, typeof items>();
  for (const item of items) {
    const section =
      item.type === 'doc'
        ? Object.keys(rootSections).find((label) => rootSections[label].docIds.includes(item.id))
        : undefined;
    if (!section) {
      result.push(item);
      continue;
    }
    if (!grouped.has(section)) {
      grouped.set(section, []);
      // Placeholder keeps the section where its first doc was generated (by sidebar_position).
      result.push({type: 'category', label: section, items: [], collapsed: true, collapsible: true});
    }
    grouped.get(section)!.push(item);
  }
  return result.map((item) =>
    item.type === 'category' && grouped.has(item.label) ? {...item, items: grouped.get(item.label)!} : item,
  );
};

